var updateRunSchema = flag.Bool("update-runschema", false, "rewrite the dashboard's generated run-file schema")

// runSchemaPath is the dashboard's copy of the run-file schema: the field
// table, the named lists, the behaviours' fields, the gates' metrics and
// the built-in templates, so the Launch page follows Go rather than a
// hand-kept list.
var runSchemaPath = filepath.Join("..", "..", "web", "src", "data", "launch", "runschema.gen.ts")

// behaviorField is one field under a workload's behaviors, as the run
// file writes it (protojson, proto names).
type behaviorField struct {
	Path   string   `json:"path"`
	Type   string   `json:"type"` // string, double, uint, bool, enum, map or a list of one (list:<type>)
	Values []string `json:"values,omitempty"`
	// Secret marks a field that holds a secret (a cohort's token): the
	// page writes it only as a ${VAR}.
	Secret bool `json:"secret,omitempty"`
}

// behaviorFields walks Behaviors in declared order.
func behaviorFields(t *testing.T) []behaviorField {
	t.Helper()
	var out []behaviorField
	var walk func(prefix string, md protoreflect.MessageDescriptor, depth int)
	walk = func(prefix string, md protoreflect.MessageDescriptor, depth int) {
		if depth > 6 {
			t.Fatalf("%s: behaviours nest too deep", prefix)
		}
		for i := 0; i < md.Fields().Len(); i++ {
			fd := md.Fields().Get(i)
			path := prefix + string(fd.Name())
			if fd.IsMap() {
				out = append(out, behaviorField{Path: path, Type: "map"})
				continue
			}
			var typ string
			var values []string
			switch fd.Kind() {
			case protoreflect.MessageKind:
				if fd.IsList() {
					walk(path+"[].", fd.Message(), depth+1)
				} else {
					walk(path+".", fd.Message(), depth+1)
				}
				continue
			case protoreflect.StringKind:
				typ = "string"
			case protoreflect.DoubleKind, protoreflect.FloatKind:
				typ = "double"
			case protoreflect.Uint32Kind, protoreflect.Uint64Kind, protoreflect.Int32Kind, protoreflect.Int64Kind:
				typ = "uint"
			case protoreflect.BoolKind:
				typ = "bool"
			case protoreflect.EnumKind:
				typ = "enum"
				for j := 0; j < fd.Enum().Values().Len(); j++ {
					if v := fd.Enum().Values().Get(j); v.Number() != 0 {
						values = append(values, string(v.Name()))
					}
				}
			default:
				t.Fatalf("%s: a %v the Launch page cannot edit", path, fd.Kind())
			}
			if fd.IsList() {
				typ = "list:" + typ
			}
			out = append(out, behaviorField{Path: path, Type: typ, Values: values, Secret: secrets.Marked(fd) || secrets.IsSecretName(string(fd.Name()))})
		}
	}
	walk("", (&orbitv1.Behaviors{}).ProtoReflect().Descriptor(), 0)
	return out
}

func renderRunSchema(t *testing.T) []byte {
	t.Helper()
	js := func(v any) string {
		b, err := json.MarshalIndent(v, "", "  ")
		if err != nil {
			t.Fatal(err)
		}
		return string(b)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/server/runschema_test.go; DO NOT EDIT.\n")
	b.WriteString("// Regenerate: go test ./internal/server -run TestRunSchema -update-runschema\n\n")
	b.WriteString("/** A run-file field's value type, as the CLI's field table has it. */\n")
	b.WriteString(`export type RunFieldType = "string" | "uint" | "float" | "bool" | "strings" | "any";` + "\n\n")
	b.WriteString("/** One run-file field, on its canonical path pattern. */\nexport interface RunFieldSpec {\n  path: string;\n  type: RunFieldType;\n  wide?: boolean;\n}\n\n")
	b.WriteString("/** Every run-file field (internal/target's field table), by path. */\nexport const RUN_FIELDS: readonly RunFieldSpec[] = [\n")
	for _, f := range target.RunFieldSpecs() {
		line, err := json.Marshal(f)
		if err != nil {
			t.Fatal(err)
		}
		fmt.Fprintf(&b, "  %s,\n", line)
	}
	b.WriteString("];\n\n")
	fmt.Fprintf(&b, "/** The run file's lists whose elements are named. */\nexport const RUN_NAMED_LISTS: readonly string[] = %s;\n\n", js(target.RunNamedLists()))
	b.WriteString("/** One field under a workload's behaviors (orbit.v1.Behaviors, proto names). */\nexport interface BehaviorField {\n  path: string;\n  type: string;\n  values?: string[];\n  secret?: boolean;\n}\n\n")
	b.WriteString("/** Every behaviours field, in declared order. */\nexport const BEHAVIOR_FIELDS: readonly BehaviorField[] = [\n")
	for _, f := range behaviorFields(t) {
		line, err := json.Marshal(f)
		if err != nil {
			t.Fatal(err)
		}
		fmt.Fprintf(&b, "  %s,\n", line)
	}
	b.WriteString("];\n\n")
	quantiles := make([]string, 0, len(latencyQuantiles))
	for q := range latencyQuantiles {
		quantiles = append(quantiles, q)
	}
	sort.Strings(quantiles)
	procs := slices.Clone(gateProcedures)
	fmt.Fprintf(&b, "/** An SLO gate's metrics: these two, or <procedure>.<quantile>_ms. */\nexport const GATE_METRICS: readonly string[] = %s;\n\n", js([]string{metricSuccessRatio, metricAchievedRate}))
	fmt.Fprintf(&b, "/** The procedures a latency gate names. */\nexport const GATE_PROCEDURES: readonly string[] = %s;\n\n", js(procs))
	fmt.Fprintf(&b, "/** The quantiles a latency gate names. */\nexport const GATE_QUANTILES: readonly string[] = %s;\n\n", js(quantiles))
	ops := make([]string, 0, len(opText))
	for _, o := range opText {
		ops = append(ops, o)
	}
	sort.Strings(ops)
	fmt.Fprintf(&b, "/** An SLO gate's comparisons. */\nexport const GATE_OPS: readonly string[] = %s;\n\n", js(ops))
	yamlKeys := func(v any) []string {
		var out []string
		rt := reflect.TypeOf(v)
		for i := 0; i < rt.NumField(); i++ {
			k, _, _ := strings.Cut(rt.Field(i).Tag.Get("yaml"), ",")
			out = append(out, k)
		}
		return out
	}
	fmt.Fprintf(&b, "/** An inline expected-failures list's keys (docs/conformance/expected-failures.md). */\nexport const EXPECTED_KEYS: readonly string[] = %s;\n\n", js(yamlKeys(conformance.ExpectedFailures{})))
	fmt.Fprintf(&b, "/** One expected-failures entry's keys, each required. */\nexport const EXPECTED_ENTRY_KEYS: readonly string[] = %s;\n\n", js(yamlKeys(conformance.ExpectedFailureEntry{})))
	var phases []string
	pv := orbitv1.WorkloadPhase(0).Descriptor().Values()
	for i := 0; i < pv.Len(); i++ {
		if v := pv.Get(i); v.Number() != 0 {
			phases = append(phases, strings.ToLower(strings.TrimPrefix(string(v.Name()), "WORKLOAD_PHASE_")))
		}
	}
	fmt.Fprintf(&b, "/** A workload's start: {after: <workload>, phase: one of these}. */\nexport const START_PHASES: readonly string[] = %s;\n\n", js(phases))
	names := make([]string, 0, len(secrets.Names))
	for n := range secrets.Names {
		names = append(names, n)
	}
	sort.Strings(names)
	fmt.Fprintf(&b, "/** The names that hold secrets, normalised (internal/secrets.Names). */\nexport const SECRET_NAMES: readonly string[] = %s;\n\n", js(names))
	vectors := secrets.NameCases
	// The runes Go lower-cases (unicode.ToLower) to an ASCII letter, beyond
	// A-Z. A secret name is ASCII, so these are the only lowerings a page
	// must do as Go does to match it: JS's toLowerCase differs on some
	// (İ becomes "i̇", two runes).
	asciiLower := map[string]string{}
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if r >= 'A' && r <= 'Z' {
			continue
		}
		if l := unicode.ToLower(r); l != r && l < 0x80 {
			asciiLower[string(r)] = string(l)
		}
	}
	fmt.Fprintf(&b, "/** Runes Go's unicode.ToLower makes an ASCII letter, beyond A-Z (secrets' splitWords lowers with it). */\nexport const ASCII_LOWER: Readonly<Record<string, string>> = %s;\n\n", js(asciiLower))
	fmt.Fprintf(&b, "/** secrets.NameCases: the names secrets.IsSecretName is held to, for the page's port of it. */\nexport const SECRET_NAME_VECTORS: Readonly<Record<string, boolean>> = %s;\n\n", js(vectors))
	templates := map[string]string{}
	for _, n := range plan.Templates() {
		text, err := plan.TemplateText(n)
		if err != nil {
			t.Fatal(err)
		}
		templates[n] = text
	}
	fmt.Fprintf(&b, "/** The built-in templates (orbit test), as written. */\nexport const TEMPLATES: Readonly<Record<string, string>> = %s;\n", js(templates))
	return b.Bytes()
}

// The dashboard's generated run-file schema is current: a run-file field,
// a behaviour, a gate metric or a template changed in Go fails here until
// it is regenerated.
func TestRunSchema(t *testing.T) {
	want := renderRunSchema(t)
	if *updateRunSchema {
		if err := os.MkdirAll(filepath.Dir(runSchemaPath), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(runSchemaPath, want, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(runSchemaPath)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("%s is stale; go test ./internal/server -run TestRunSchema -update-runschema", runSchemaPath)
	}
}
