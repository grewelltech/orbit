package conformance

import (
	"fmt"
	"strings"
)

// provenanceBase is where the checks' provenance files are published.
const provenanceBase = "https://github.com/grewelltech/orbit/blob/main/docs/conformance/provenance/"

// SiteTests are the checks the documentation site has a page for: the
// default run's, then every pack's, since a run links each check it runs
// to its page.
func SiteTests() []Test {
	all := NewRegistry().Tests()
	for _, p := range builtinPacks {
		all = append(all, p.Checks...)
	}
	return all
}

// SitePages renders the documentation site's conformance pages, keyed by
// file name relative to the site's conformance/checks directory: an index
// listing the checks, then one page per check (DocURL) with its summary,
// group, clauses and every outcome it can report, each outcome anchored by
// its ID (OutcomeURL). A golden test fails when the committed pages are
// stale; regenerate with go generate ./internal/conformance.
func SitePages(tests []Test) map[string]string {
	owner := map[Procedure]string{}
	for _, t := range tests {
		for _, p := range OwnsOf(t) {
			owner[p] = t.ID()
		}
	}
	pages := map[string]string{"index.md": siteIndex(tests)}
	for _, t := range tests {
		pages[strings.ToLower(t.ID())+".md"] = sitePage(t, owner)
	}
	return pages
}

// siteIndex is the checks' index page: one row per check, in run order.
func siteIndex(tests []Test) string {
	var b strings.Builder
	b.WriteString("---\ntitle: Conformance checks\ndescription: Every check ORBIT's conformance suite runs, what it asks of the core and the clauses it rests on.\n---\n\n")
	b.WriteString("<!-- Generated by `go generate ./internal/conformance`; do not edit. -->\n\n")
	b.WriteString("Each check drives one procedure or one malformed message at a live core and judges the answer against the 3GPP clauses it cites. `orbit conformance` links each check it runs to its page here.\n\n")
	b.WriteString("| Check | Category | What it asks | Verdict class |\n|---|---|---|---|\n")
	for _, t := range tests {
		fmt.Fprintf(&b, "| [%s](%s) | %s | %s | %s |\n", t.ID(), "./"+strings.ToLower(t.ID())+"/",
			siteEscape(Category(groupString(t))), siteEscape(SummaryOf(t.ID())), VerdictClass(t))
	}
	return b.String()
}

// sitePage is one check's page.
func sitePage(t Test, owner map[Procedure]string) string {
	var b strings.Builder
	summary := SummaryOf(t.ID())
	fmt.Fprintf(&b, "---\ntitle: %s\ndescription: %q\n---\n\n", t.ID(), summary)
	b.WriteString("<!-- Generated by `go generate ./internal/conformance`; do not edit. -->\n\n")
	fmt.Fprintf(&b, "**%s**\n\n", siteEscape(summary))
	tags := joinTags(TagsOf(t))
	if tags == "" {
		tags = "none"
	}
	b.WriteString("| | |\n|---|---|\n")
	fmt.Fprintf(&b, "| Group | %s |\n", siteEscape(groupString(t)))
	fmt.Fprintf(&b, "| Tags | %s |\n", siteEscape(tags))
	fmt.Fprintf(&b, "| Verdict class | %s |\n", VerdictClass(t))
	fmt.Fprintf(&b, "| Requires | %s |\n", MinRelease(t))
	fmt.Fprintf(&b, "| Up to | %s at the default `--per-test-timeout` |\n", ExpectedDuration(t, DefaultPerTestTimeout))
	fmt.Fprintf(&b, "| Phase | %s |\n", PhaseOf(t))
	if owned := OwnsOf(t); len(owned) > 0 {
		fmt.Fprintf(&b, "| Owns | %s |\n", joinProcedures(owned))
	}
	needs := "no procedure first"
	if needed := NeedsOf(t).Procedures; len(needed) > 0 {
		needs = joinProcedures(needed)
	}
	fmt.Fprintf(&b, "| Needs | %s |\n", needs)

	b.WriteString("\n## Clauses\n\n")
	for _, r := range t.SpecRefs() {
		fmt.Fprintf(&b, "- %s\n", siteEscape(r.String()))
	}
	fmt.Fprintf(&b, "\nThe quoted normative text and the release history of each clause are in the check's [provenance](%s%s.md).\n", provenanceBase, t.ID())

	b.WriteString("\n## Outcomes\n\n")
	b.WriteString("Every result is one of these outcomes. A run links a result that is not a PASS to its outcome here.\n\n")
	b.WriteString("| Outcome | Verdict | Basis | The core |\n|---|---|---|---|\n")
	refs := map[string]SpecRef{}
	for _, r := range t.SpecRefs() {
		refs[r.Key()] = r
	}
	for _, o := range AllOutcomes(t) {
		fmt.Fprintf(&b, "| <span id=\"%s\"></span>`%s` | %s | %s | %s |\n", o.ID, o.ID, o.Verdict,
			siteEscape(outcomeBasis(o, refs, owner)), siteEscape(o.Summary))
	}
	return b.String()
}

// groupString is t's group path in the default target release, "" when it
// has none.
func groupString(t Test) string {
	if g, err := GroupOf(t, 0); err == nil {
		return g.String()
	}
	return ""
}

// siteEscape keeps generated text from breaking a page: a "|" from ending a
// table cell and a "<" from opening an HTML tag.
func siteEscape(s string) string { return strings.ReplaceAll(mdEscape(s), "<", "&lt;") }
