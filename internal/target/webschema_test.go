var updateWeb = flag.Bool("update", false, "rewrite the dashboard's generated target schema and the round-trip fixtures")

// webSchemaPath is the dashboard's copy of the target schema: the field
// table, the named lists, the name rule and the built-in defaults, so the
// browser's editor follows Go rather than a hand-kept list.
var webSchemaPath = filepath.Join("..", "..", "web", "src", "data", "targets", "schema.gen.ts")

// webField is one target field as the dashboard sees it.
type webField struct {
	Path   string `json:"path"`
	Type   string `json:"type"`
	Secret bool   `json:"secret"`
	// Editable is false for a field the document must leave empty (ran.node).
	Editable bool `json:"editable"`
}

// webFields walks the Target struct in its declared order, so the editor
// shows fields as a target file has them, and checks each against the
// field table: a field the table has and the struct does not (or the
// reverse) fails here.
func webFields(t *testing.T) []webField {
	t.Helper()
	var out []webField
	var walk func(prefix string, rt reflect.Type)
	walk = func(prefix string, rt reflect.Type) {
		for i := 0; i < rt.NumField(); i++ {
			sf := rt.Field(i)
			key, _, _ := strings.Cut(sf.Tag.Get("yaml"), ",")
			if key == "" || key == "-" {
				continue
			}
			path := prefix + key
			ft := sf.Type
			switch {
			case ft.Kind() == reflect.Struct:
				walk(path+".", ft)
				continue
			case ft.Kind() == reflect.Slice && ft.Elem().Kind() == reflect.Struct && namedLists[path]:
				walk(path+"[].", ft.Elem())
				continue
			}
			f, ok := fields[path]
			if !ok || !f.target {
				t.Fatalf("%s is in the Target struct but not a target field in paths.go", path)
			}
			var typ string
			switch f.typ {
			case tString:
				typ = "string"
			case tUint:
				typ = "uint"
			case tStrings:
				typ = "strings"
			case tSlices:
				typ = "slices"
			default:
				t.Fatalf("%s: a target field of a type the dashboard does not edit (%d)", path, f.typ)
			}
			out = append(out, webField{Path: path, Type: typ, Secret: f.secret, Editable: path != "ran.node"})
		}
	}
	walk("", reflect.TypeOf(Target{}))
	seen := map[string]bool{}
	for _, f := range out {
		seen[f.Path] = true
	}
	for p, f := range fields {
		// core.slices[].sst and .sd are the flags' paths into the first
		// slice; the document edits core.slices whole.
		if f.target && !seen[p] && !strings.HasPrefix(p, "core.slices[]") {
			t.Fatalf("%s is a target field in paths.go but not in the Target struct", p)
		}
	}
	return out
}

// webDefaults is DefaultInput as the dashboard shows it: every value as a
// string, as the browser reads a document.
func webDefaults(t *testing.T) map[string]any {
	t.Helper()
	out := map[string]any{}
	for _, s := range DefaultInput().Settings {
		switch v := s.Value.(type) {
		case string:
			out[s.Path] = v
		case uint64:
			out[s.Path] = strconv.FormatUint(v, 10)
		case []Slice:
			var sl []map[string]string
			for _, x := range v {
				m := map[string]string{"sst": strconv.FormatUint(uint64(x.SST), 10)}
				if x.SD != "" {
					m["sd"] = x.SD
				}
				sl = append(sl, m)
			}
			out[s.Path] = sl
		default:
			t.Fatalf("default %s: a %T the dashboard cannot show", s.Path, s.Value)
		}
	}
	return out
}

func renderWebSchema(t *testing.T) []byte {
	t.Helper()
	js := func(v any) string {
		b, err := json.MarshalIndent(v, "", "  ")
		if err != nil {
			t.Fatal(err)
		}
		return string(b)
	}
	var lists []string
	for p := range namedLists {
		if _, ok := fields[p+"[].name"]; ok && fields[p+"[].name"].target {
			lists = append(lists, p)
		}
	}
	sortStrings(lists)
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/target/webschema_test.go; DO NOT EDIT.\n")
	b.WriteString("// Regenerate: go test ./internal/target -run TestWebSchema -update\n\n")
	b.WriteString("/** A target field's value type, as the CLI's field table has it. */\n")
	b.WriteString(`export type FieldType = "string" | "uint" | "strings" | "slices";` + "\n\n")
	b.WriteString("/** One field of a target document, on its canonical path pattern. */\n")
	b.WriteString("export interface FieldSpec {\n  path: string;\n  type: FieldType;\n  secret: boolean;\n  editable: boolean;\n}\n\n")
	b.WriteString("/** Every target field, in the order a target file has them. */\nexport const TARGET_FIELDS: readonly FieldSpec[] = [\n")
	for _, f := range webFields(t) {
		line, err := json.Marshal(f)
		if err != nil {
			t.Fatal(err)
		}
		fmt.Fprintf(&b, "  %s,\n", line)
	}
	b.WriteString("];\n\n")
	fmt.Fprintf(&b, "/** The lists whose elements are named (and merge by name). */\nexport const NAMED_LISTS: readonly string[] = %s;\n\n", js(lists))
	var sliceKeys []string
	for p, f := range fields {
		if f.target && strings.HasPrefix(p, "core.slices[].") {
			sliceKeys = append(sliceKeys, strings.TrimPrefix(p, "core.slices[]."))
		}
	}
	sortStrings(sliceKeys)
	fmt.Fprintf(&b, "/** The keys of one core.slices entry. */\nexport const SLICE_KEYS: readonly string[] = %s;\n\n", js(sliceKeys))
	fmt.Fprintf(&b, "/** A target or responder name: it becomes a file name. */\nexport const VALID_NAME = /%s/;\n\n", validName.String())
	fmt.Fprintf(&b, "/** The built-in defaults (target.DefaultInput), applied under the document. */\nexport const DEFAULTS: Readonly<Record<string, unknown>> = %s;\n", js(webDefaults(t)))
	return b.Bytes()
}

func sortStrings(s []string) {
	for i := 1; i < len(s); i++ {
		for j := i; j > 0 && s[j] < s[j-1]; j-- {
			s[j], s[j-1] = s[j-1], s[j]
		}
	}
}

// The dashboard's generated schema is current: a field added to the
// target (or a default changed) fails here until it is regenerated, so the
// browser never edits a stale schema silently.
func TestWebSchema(t *testing.T) {
	want := renderWebSchema(t)
	if *updateWeb {
		if err := os.WriteFile(webSchemaPath, want, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(webSchemaPath)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("%s is stale; go test ./internal/target -run TestWebSchema -update", webSchemaPath)
	}
}
